// Regenerate after editing colors in globals.css. Only color declarations are
// derived; responsive layout and the original male theme remain untouched.
import fs from 'node:fs';
import postcss from 'postcss';
const source = postcss.parse(fs.readFileSync(new URL('../app/globals.css', import.meta.url), 'utf8'));
function hsl(hex) {
  let value=hex.slice(1);if(value.length===3||value.length===4)value=[...value].map(c=>c+c).join('');
  const [r,g,b]=[0,2,4].map(i=>parseInt(value.slice(i,i+2),16)/255),max=Math.max(r,g,b),min=Math.min(r,g,b),delta=max-min,l=(max+min)/2;
  let h=0,s=0;if(delta){s=delta/(1-Math.abs(2*l-1));h=(max===r?(g-b)/delta+(g<b?6:0):max===g?(b-r)/delta+2:(r-g)/delta+4)*60;}
  return {h,s,l,alpha:value.slice(6)};
}
function hex(h,s,l,alpha='') {
  const c=(1-Math.abs(2*l-1))*s,x=c*(1-Math.abs((h/60)%2-1)),m=l-c/2;
  const v=h<60?[c,x,0]:h<120?[x,c,0]:h<180?[0,c,x]:h<240?[0,x,c]:h<300?[x,0,c]:[c,0,x];
  return '#'+v.map(v=>Math.round((v+m)*255).toString(16).padStart(2,'0')).join('')+alpha;
}
function role(prop) {
  if(/shadow/.test(prop))return 'shadow';
  if(/border|outline|ring|divider/.test(prop))return 'edge';
  if(/background|popover$|soft|surface|crystal-face|crystal-gloss/.test(prop))return 'surface';
  if(/primary$|mode-color|discovery-accent|challenge|accent-color/.test(prop))return 'accent';
  return 'ink';
}
function recolor(value,prop,theme) {
  const kind=role(prop);
  return value.replace(/#[\da-f]{8}\b|#[\da-f]{6}\b|#[\da-f]{4}\b|#[\da-f]{3}\b|\bwhite\b|\bblack\b/gi,original=>{
    const c=hsl(original==='white'?'#ffffff':original==='black'?'#000000':original);
    const cool=c.h>=175&&c.h<=270;
    if(theme==='female')return cool?hex(335,Math.min(c.s,.55),c.l,c.alpha):original;
    // Keep error/success/attention hues distinguishable on dark surfaces.
    const hue=cool||c.s<.12?202:c.h;
    if(kind==='shadow')return hex(190,.85,.55,c.alpha||'35');
    if(kind==='surface')return hex(hue,c.l>.72?.5:Math.min(.8,Math.max(.5,c.s)),c.l>.72?.095+(1-c.l)*.15:Math.max(.065,c.l*.62),c.alpha);
    if(kind==='edge')return hex(hue,.45,.3,c.alpha);
    if(kind==='accent')return hex(cool?188:hue,.8,.7,c.alpha);
    return c.l>.92?original:hex(hue,Math.min(.7,Math.max(.22,c.s)),c.l<.3?.9:.77,c.alpha);
  });
}
function derive(container,theme){
  const output=postcss.root();
  for(const node of container.nodes??[]){
    if(node.type==='atrule'){
      if(!['media','supports'].includes(node.name)||/print/.test(node.params))continue;
      const children=derive(node,theme);if(children.nodes.length){const next=node.clone({nodes:[]});next.append(children.nodes);output.append(next);}continue;
    }
    if(node.type!=='rule'||/lark-register-button|lark-button-logo/.test(node.selector))continue;
    const declarations=[];
    for(const declaration of node.nodes??[]){
      if(declaration.type!=='decl'||!(/color|background|border|outline|shadow|fill|stroke/.test(declaration.prop)||declaration.prop.startsWith('--')))continue;
      const value=recolor(declaration.value,declaration.prop,theme);
      if(value!==declaration.value)declarations.push(declaration.clone({value}));
    }
    if(!declarations.length)continue;
    const scope=`html[data-navigator-theme="${theme}"]`;
    const selectors=node.selectors.map(selector=>/^(?:html|:root)(?![\w-])/.test(selector)?selector.replace(/^(?:html|:root)/,scope):`${scope} ${selector}`);
    output.append(postcss.rule({selector:selectors.join(', '),nodes:declarations}));
  }
  return output;
}
const output=['/* Generated by scripts/generate-navigator-palettes.mjs. Male uses globals.css unchanged. */'];
for(const theme of ['female','anime'])output.push(derive(source,theme).toString());
fs.writeFileSync(new URL('../app/navigator-palettes.css',import.meta.url),output.join('\n'));
